@Injectable({ providedIn: 'root' })
export class I18nService {
  currentLang = signal<Lang>(this.getStored());

  constructor() {
    document.documentElement.dir = this.currentLang() === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = this.currentLang();
  }

  t(key: string): string {
    return translations[this.currentLang()]?.[key] || translations.en[key] || key;
  }

  setLang(lang: Lang): void {
    this.currentLang.set(lang);
    localStorage.setItem('admin_lang', lang);
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  }

  get availableLanguages(): { code: Lang; label: string; icon: string }[] {
    return [
      { code: 'en', label: 'English', icon: '🇺🇸' },
      { code: 'fr', label: 'Français', icon: '🇫🇷' },
      { code: 'ar', label: 'العربية', icon: '🇸🇦' },
    ];
  }

  private getStored(): Lang {
    try {
      const stored = localStorage.getItem('admin_lang');
      if (stored && ['en', 'fr', 'ar'].includes(stored)) return stored as Lang;
    } catch {}
    return 'en';
  }
}
